private void loadPurchases() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblPurchases.getModel();

    model.setRowCount(0);

    for (Purchase purchase : dao.getAllPurchases()) {

        model.addRow(new Object[]{
            purchase.getPurchaseId(),
            purchase.getSupplierId(),
            purchase.getEmployeeId(),
            purchase.getPurchaseDate(),
            purchase.getTotalAmount()
        });
    }
}
    private void btnAddPurchaseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddPurchaseActionPerformed
        int supplierId = Integer.parseInt(txtSupplierId.getText());
int employeeId = Integer.parseInt(txtEmployeeId.getText());
String purchaseDate = txtPurchaseDate.getText();
double totalAmount = Double.parseDouble(txtTotalAmount.getText());

Purchase purchase = new Purchase(
        0,
        supplierId,
        employeeId,
        purchaseDate,
        totalAmount
);

if (dao.addPurchase(purchase)) {

    JOptionPane.showMessageDialog(
            this,
            "Purchase Added Successfully!"
    );

    loadPurchases();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to Add Purchase!"
    );
}
    }//GEN-LAST:event_btnAddPurchaseActionPerformed

    private void btnUpdatePurchaseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdatePurchaseActionPerformed
        if (txtPurchaseId.getText().isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Please select a purchase first!"
    );

    return;
}

int purchaseId = Integer.parseInt(txtPurchaseId.getText());
int supplierId = Integer.parseInt(txtSupplierId.getText());
int employeeId = Integer.parseInt(txtEmployeeId.getText());
String purchaseDate = txtPurchaseDate.getText();
double totalAmount = Double.parseDouble(txtTotalAmount.getText());

Purchase purchase = new Purchase(
        purchaseId,
        supplierId,
        employeeId,
        purchaseDate,
        totalAmount
);

if (dao.updatePurchase(purchase)) {

    JOptionPane.showMessageDialog(
            this,
            "Purchase Updated Successfully!"
    );

    loadPurchases();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to Update Purchase!"
    );
}
    }//GEN-LAST:event_btnUpdatePurchaseActionPerformed

    private void btnDeletePurchaseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletePurchaseActionPerformed
      if (txtPurchaseId.getText().isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Please select a purchase first!"
    );

    return;
}

int purchaseId = Integer.parseInt(txtPurchaseId.getText());

if (dao.deletePurchase(purchaseId)) {

    JOptionPane.showMessageDialog(
            this,
            "Purchase Deleted Successfully!"
    );

    loadPurchases();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to Delete Purchase!"
    );
}
    }//GEN-LAST:event_btnDeletePurchaseActionPerformed

    private void tblPurchasesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPurchasesMouseClicked
        int row = tblPurchases.getSelectedRow();

if (row >= 0) {

    txtPurchaseId.setText(
            tblPurchases.getValueAt(row, 0).toString()
    );

    txtSupplierId.setText(
            tblPurchases.getValueAt(row, 1).toString()
    );

    txtEmployeeId.setText(
            tblPurchases.getValueAt(row, 2).toString()
    );

    txtPurchaseDate.setText(
            tblPurchases.getValueAt(row, 3).toString()
    );

    txtTotalAmount.setText(
            tblPurchases.getValueAt(row, 4).toString()
    );
}
    }//GEN-LAST:event_tblPurchasesMouseClicked

