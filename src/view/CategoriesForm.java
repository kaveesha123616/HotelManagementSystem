    private void btnAddCategoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCategoryActionPerformed
       String categoryName = txtCategoryName.getText();

Category category = new Category(
        0,
        categoryName
);

if (dao.addCategory(category)) {

    JOptionPane.showMessageDialog(
            this,
            "Category Added Successfully!"
    );
        loadCategories();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to Add Category!"
    );
}
    }//GEN-LAST:event_btnAddCategoryActionPerformed

    private void btnUpdateCategoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateCategoryActionPerformed
     if (txtCategoryId.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please select a category first!");
    return;
}

int categoryId = Integer.parseInt(txtCategoryId.getText());
String categoryName = txtCategoryName.getText();

Category category = new Category(
        categoryId,
        categoryName
);

if (dao.updateCategory(category)) {

    JOptionPane.showMessageDialog(
            this,
            "Category Updated Successfully!"
    );

    loadCategories();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to Update Category!"
    );
}
    }//GEN-LAST:event_btnUpdateCategoryActionPerformed

    private void btnDeleteCategoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteCategoryActionPerformed
        if (txtCategoryId.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please select a category first!");
    return;
}

int categoryId = Integer.parseInt(txtCategoryId.getText());

if (dao.deleteCategory(categoryId)) {

    JOptionPane.showMessageDialog(
            this,
            "Category Deleted Successfully!"
    );

    loadCategories();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Failed to Delete Category!"
    );
}
    }
private void loadCategories() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblCategories.getModel();

    model.setRowCount(0);

    for (Category category : dao.getAllCategories()) {

        model.addRow(new Object[]{
            category.getCategoryId(),
            category.getCategoryName()
        });
    }

    }//GEN-LAST:event_btnDeleteCategoryActionPerformed

    private void tblCategoriesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCategoriesMouseClicked
       

    int row = tblCategories.getSelectedRow();

    if (row >= 0) {

        txtCategoryId.setText(
                tblCategories.getValueAt(row, 0).toString()
        );

        txtCategoryName.setText(
                tblCategories.getValueAt(row, 1).toString()
        );
    }

    }//GEN-LAST:event_tblCategoriesMouseClicked

