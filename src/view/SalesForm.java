    private void btnAddSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddSaleActionPerformed
                                                 

    int customerId = Integer.parseInt(txtCustomerId.getText());
    int employeeId = Integer.parseInt(txtEmployeeId.getText());
    String saleDate = txtSaleDate.getText();
    double totalAmount = Double.parseDouble(txtTotalAmount.getText());
    String paymentStatus = cmbPaymentStatus.getSelectedItem().toString();

    Sale sale = new Sale(
            0,
            customerId,
            employeeId,
            saleDate,
            totalAmount,
            paymentStatus
    );

    SaleDAO dao = new SaleDAO();

    if (dao.addSale(sale)) {

        JOptionPane.showMessageDialog(
                this,
                "Sale Added Successfully!"
        );

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to Add Sale!"
        );
    }

    }//GEN-LAST:event_btnAddSaleActionPerformed

    private void btnUpdateSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateSaleActionPerformed
        

    if (txtSaleId.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a sale first!");
        return;
    }

    int saleId = Integer.parseInt(txtSaleId.getText());
    int customerId = Integer.parseInt(txtCustomerId.getText());
    int employeeId = Integer.parseInt(txtEmployeeId.getText());
    String saleDate = txtSaleDate.getText();
    double totalAmount = Double.parseDouble(txtTotalAmount.getText());
    String paymentStatus = cmbPaymentStatus.getSelectedItem().toString();

    Sale sale = new Sale(
            saleId,
            customerId,
            employeeId,
            saleDate,
            totalAmount,
            paymentStatus
    );

    SaleDAO dao = new SaleDAO();

    if (dao.updateSale(sale)) {

        JOptionPane.showMessageDialog(
                this,
                "Sale Updated Successfully!"
        );

        loadSales();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to Update Sale!"
        );
    }

    }//GEN-LAST:event_btnUpdateSaleActionPerformed

    private void tblSalesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSalesMouseClicked
     

    int row = tblSales.getSelectedRow();

    if (row >= 0) {

        txtSaleId.setText(
                tblSales.getValueAt(row, 0).toString()
        );

        txtCustomerId.setText(
                tblSales.getValueAt(row, 1).toString()
        );

        txtEmployeeId.setText(
                tblSales.getValueAt(row, 2).toString()
        );

        txtSaleDate.setText(
                tblSales.getValueAt(row, 3).toString()
        );

        txtTotalAmount.setText(
                tblSales.getValueAt(row, 4).toString()
        );

        cmbPaymentStatus.setSelectedItem(
                tblSales.getValueAt(row, 5).toString()
        );
    }

    }//GEN-LAST:event_tblSalesMouseClicked

    private void btnDeleteSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteSaleActionPerformed
                                                    

    if (txtSaleId.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please select a sale first!");
        return;
    }

    int saleId = Integer.parseInt(txtSaleId.getText());

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this sale?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm == JOptionPane.YES_OPTION) {

        SaleDAO dao = new SaleDAO();

        if (dao.deleteSale(saleId)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Sale Deleted Successfully!"
            );

            loadSales();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to Delete Sale!"
            );
        }
}

    }//GEN-LAST:event_btnDeleteSaleActionPerformed

