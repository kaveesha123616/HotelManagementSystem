    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                                      
    try {

        java.io.InputStream reportStream =
                getClass().getResourceAsStream("/view/SalesReport.jrxml");

        if (reportStream == null) {
            JOptionPane.showMessageDialog(this,
                    "SalesReport.jrxml file not found!");
            return;
        }

        net.sf.jasperreports.engine.JasperReport jasperReport =
                net.sf.jasperreports.engine.JasperCompileManager
                        .compileReport(reportStream);

        java.sql.Connection con =
                database.DBConnection.getConnection();

        java.util.Map<String, Object> parameters =
                new java.util.HashMap<>();

        net.sf.jasperreports.engine.JasperPrint jasperPrint =
                net.sf.jasperreports.engine.JasperFillManager
                        .fillReport(jasperReport, parameters, con);

        net.sf.jasperreports.view.JasperViewer
                .viewReport(jasperPrint, false);

        con.close();
        reportStream.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Report Error:\n" + e.getMessage());
        e.printStackTrace();
    }
                             
    }//GEN-LAST:event_jButton1ActionPerformed

