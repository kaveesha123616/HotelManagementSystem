   private void loadSales() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblSales.getModel();

    model.setRowCount(0);

    SaleDAO dao = new SaleDAO();

    for (Sale sale : dao.getAllSales()) {

        model.addRow(new Object[]{
            sale.getSaleId(),
            sale.getCustomerId(),
            sale.getEmployeeId(),
            sale.getSaleDate(),
            sale.getTotalAmount(),
            sale.getPaymentStatus()
        });
    }
} 

