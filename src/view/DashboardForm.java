    private void loadDashboardCounts() {

    try {

        // Total Customers
        String sql = "SELECT COUNT(*) FROM customers";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement pst = con.prepareStatement(sql);
             java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                lblCustomerCount.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // Total Products
        sql = "SELECT COUNT(*) FROM products";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement pst = con.prepareStatement(sql);
             java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                lblProductCount.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // Total Sales
        sql = "SELECT COUNT(*) FROM sales";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement pst = con.prepareStatement(sql);
             java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                lblSalesCount.setText(String.valueOf(rs.getInt(1)));
            }
        }

        // Total Payments
        sql = "SELECT COUNT(*) FROM payments";

        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement pst = con.prepareStatement(sql);
             java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                lblPaymentCount.setText(String.valueOf(rs.getInt(1)));
            }
        }

    } catch (Exception e) {
        e.printStackTrace();
    }
}

  

        

        

        

