    private void btnAddDetailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddDetailActionPerformed
        try {

    int saleId = Integer.parseInt(
            cmbSale.getSelectedItem().toString()
    );

    int productId = Integer.parseInt(
            cmbProduct.getSelectedItem().toString()
    );

    int quantity = Integer.parseInt(
            txtQuantity.getText()
    );

    double unitPrice = Double.parseDouble(
            txtUnitPrice.getText()
    );

    double subtotal = quantity * unitPrice;

    txtSubtotal.setText(
            String.valueOf(subtotal)
    );

    SaleDetail detail = new SaleDetail();

    detail.setSaleId(saleId);
    detail.setProductId(productId);
    detail.setQuantity(quantity);
    detail.setUnitPrice(unitPrice);
    detail.setSubtotal(subtotal);

    if (service.addSaleDetail(detail)) {

        JOptionPane.showMessageDialog(
                this,
                "Sale Detail Added Successfully!"
        );

        loadSaleDetails();
        clearFields();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to Add Sale Detail!"
        );
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
            this,
            "Please enter valid numbers!"
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage()
    );
}
    }//GEN-LAST:event_btnAddDetailActionPerformed

