   private void loadSales() {

    cmbSale.removeAllItems();

    SaleDAO dao = new SaleDAO();

    for (Sale sale : dao.getAllSales()) {

        cmbSale.addItem(
            String.valueOf(sale.getSaleId())
        );
    }
}
   private void loadProducts() {

    cmbProduct.removeAllItems();

    ProductDAO dao = new ProductDAO();

    for (Product product : dao.getAllProducts()) {

        cmbProduct.addItem(
            String.valueOf(product.getProductId())
        );
    }
}
   private void loadSaleDetails() {

    java.util.List<SaleDetail> details =
            service.getAllSaleDetails();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    for (SaleDetail detail : details) {

        model.addRow(new Object[]{
            detail.getDetailId(),
            detail.getSaleId(),
            detail.getProductId(),
            detail.getQuantity(),
            detail.getUnitPrice(),
            detail.getSubtotal()
        });
    }
   }
    private void clearFields() {

    if (cmbSale.getItemCount() > 0) {
        cmbSale.setSelectedIndex(0);
    }

    if (cmbProduct.getItemCount() > 0) {
        cmbProduct.setSelectedIndex(0);
    }

    txtQuantity.setText("");
    txtUnitPrice.setText("");
    txtSubtotal.setText("");

    selectedDetailId = -1;

    jTable1.clearSelection();
}


