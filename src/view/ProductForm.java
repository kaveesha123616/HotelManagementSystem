    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
    String productIdText = txtProductId.getText();

if (productIdText.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please select a product first!");
    return;
}

int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this product?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
);

if (confirm == JOptionPane.YES_OPTION) {

    try {

        int productId = Integer.parseInt(productIdText);

        boolean success = productService.deleteProduct(productId);

        if (success) {

            JOptionPane.showMessageDialog(this,
                    "Product Deleted Successfully!");

            loadProducts();

            txtProductId.setText("");
            txtProductName.setText("");
            txtCategory.setText("");
            txtBuyingPrice.setText("");
            txtSellingPrice.setText("");
            txtQuantity.setText("");
            cmbStatus.setSelectedIndex(0);

        } else {

            JOptionPane.showMessageDialog(this,
                    "Failed to delete product!");
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Invalid Product ID!");
    }
}    
    }//GEN-LAST:event_btnDeleteProductActionPerformed
private void loadProducts() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblProducts.getModel();

    model.setRowCount(0);

    java.util.List<Product> products = productService.getAllProducts();

    for (Product product : products) {

        model.addRow(new Object[]{
            product.getProductId(),
            product.getProductName(),
            product.getCategory(),
            product.getBuyingPrice(),
            product.getSellingPrice(),
            product.getQuantity(),
            product.getStatus()
        });
    }
}
    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed
   String productName = txtProductName.getText();
String category = txtCategory.getText();
String buyingPriceText = txtBuyingPrice.getText();
String sellingPriceText = txtSellingPrice.getText();
String quantityText = txtQuantity.getText();
String status = cmbStatus.getSelectedItem().toString();

if (productName.isEmpty() || category.isEmpty()
        || buyingPriceText.isEmpty() || sellingPriceText.isEmpty()
        || quantityText.isEmpty()) {

    JOptionPane.showMessageDialog(this, "Please fill all fields!");
    return;
}

try {

    double buyingPrice = Double.parseDouble(buyingPriceText);
    double sellingPrice = Double.parseDouble(sellingPriceText);
    int quantity = Integer.parseInt(quantityText);

    if (buyingPrice < 0 || sellingPrice < 0 || quantity < 0) {
        JOptionPane.showMessageDialog(this,
                "Price and quantity cannot be negative!");
        return;
    }

    Product product = new Product(
            0,
            productName,
            category,
            buyingPrice,
            sellingPrice,
            quantity,
            status
    );

    boolean success = productService.addProduct(product);

    if (success) {
        JOptionPane.showMessageDialog(this,
                "Product Added Successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Failed to add product!");
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Buying price, selling price and quantity must be valid numbers!");
}

    }//GEN-LAST:event_btnAddProductActionPerformed

