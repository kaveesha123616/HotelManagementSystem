    private void btnUpdateSupplierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateSupplierActionPerformed
     
int id = Integer.parseInt(txtSupplierId.getText());
String name = txtSupplierName.getText();
String address = txtAddress.getText();
String phone = txtPhone.getText();

if (name.isEmpty() || address.isEmpty() || phone.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please fill all fields!");
    return;
}

Supplier supplier = new Supplier(
        id,
        name,
        address,
        phone
);

if (dao.updateSupplier(supplier)) {
    JOptionPane.showMessageDialog(this, "Supplier Updated Successfully!");
    loadSuppliers();
    clearFields();
} else {
    JOptionPane.showMessageDialog(this, "Failed to Update Supplier!");
}


    }//GEN-LAST:event_btnUpdateSupplierActionPerformed

    private void btnDeleteSupplierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteSupplierActionPerformed
      
int id = Integer.parseInt(txtSupplierId.getText());

int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this supplier?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
);

if (confirm == JOptionPane.YES_OPTION) {

    if (dao.deleteSupplier(id)) {
        JOptionPane.showMessageDialog(
                this,
                "Supplier Deleted Successfully!"
        );

        loadSuppliers();
        clearFields();

    } else {
        JOptionPane.showMessageDialog(
                this,
                "Failed to Delete Supplier!"
        );
    }
}


    }//GEN-LAST:event_btnDeleteSupplierActionPerformed

    private void tblSuppliersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSuppliersMouseClicked
  
int row = tblSuppliers.getSelectedRow();

if (row >= 0) {

    txtSupplierId.setText(
            tblSuppliers.getValueAt(row, 0).toString()
    );

    txtSupplierName.setText(
            tblSuppliers.getValueAt(row, 1).toString()
    );

    txtAddress.setText(
            tblSuppliers.getValueAt(row, 2).toString()
    );

    txtPhone.setText(
            tblSuppliers.getValueAt(row, 3).toString()
    );
}


    }//GEN-LAST:event_tblSuppliersMouseClicked

