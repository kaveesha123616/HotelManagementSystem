    private void btnDeleteDetailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteDetailActionPerformed
       if (selectedDetailId == -1) {

    JOptionPane.showMessageDialog(
            this,
            "Please select a detail from the table!"
    );

    return;
}

int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this detail?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
);

if (confirm == JOptionPane.YES_OPTION) {

    if (service.deletePurchaseDetail(selectedDetailId)) {

        JOptionPane.showMessageDialog(
                this,
                "Purchase Detail Deleted Successfully!"
        );

        loadPurchaseDetails();
        clearFields();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to Delete Purchase Detail!"
        );
    }
}
    }//GEN-LAST:event_btnDeleteDetailActionPerformed

    private void btnAddDetailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddDetailActionPerformed
        try {

    if (cmbPurchase.getSelectedItem() == null ||
    cmbProduct.getSelectedItem() == null) {

    JOptionPane.showMessageDialog(
            this,
            "Please select Purchase ID and Product ID!"
    );

    return;
}

int purchaseId = Integer.parseInt(
        cmbPurchase.getSelectedItem().toString()
);

int productId = Integer.parseInt(
        cmbProduct.getSelectedItem().toString()
);

    int quantity = Integer.parseInt(
            txtQuantity.getText()
    );

    double unitPrice = Double.parseDouble(
            txtUnitPrice.getText()
    );

    double subtotal = quantity * unitPrice;

    txtSubtotal.setText(
            String.valueOf(subtotal)
    );

    PurchaseDetail detail = new PurchaseDetail();

    detail.setPurchaseId(purchaseId);
    detail.setProductId(productId);
    detail.setQuantity(quantity);
    detail.setUnitPrice(unitPrice);
    detail.setSubtotal(subtotal);

    if (service.addPurchaseDetail(detail)) {

        JOptionPane.showMessageDialog(
                this,
                "Purchase Detail Added Successfully!"
        );

        loadPurchaseDetails();
        clearFields();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to Add Purchase Detail!"
        );
    }

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
            this,
            "Please enter valid numbers!"
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage()
    );
}
    }//GEN-LAST:event_btnAddDetailActionPerformed

