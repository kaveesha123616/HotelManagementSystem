    private void loadPurchases() {

    cmbPurchase.removeAllItems();

    PurchaseDAO dao = new PurchaseDAO();

    for (Purchase purchase : dao.getAllPurchases()) {

        cmbPurchase.addItem(
                String.valueOf(purchase.getPurchaseId())
        );
    }
}
    private void loadProducts() {

    cmbProduct.removeAllItems();

    ProductDAO dao = new ProductDAO();

    for (Product product : dao.getAllProducts()) {

        cmbProduct.addItem(
                String.valueOf(product.getProductId())
        );
    }
}
    private void loadPurchaseDetails() {

    java.util.List<PurchaseDetail> details =
            service.getAllPurchaseDetails();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblPurchaseDetails.getModel();

    model.setRowCount(0);

    for (PurchaseDetail detail : details) {

        model.addRow(new Object[]{
            detail.getDetailId(),
            detail.getPurchaseId(),
            detail.getProductId(),
            detail.getQuantity(),
            detail.getUnitPrice(),
            detail.getSubtotal()
        });
    }
}
    private void clearFields() {

    if (cmbPurchase.getItemCount() > 0) {
        cmbPurchase.setSelectedIndex(0);
    }

    if (cmbProduct.getItemCount() > 0) {
        cmbProduct.setSelectedIndex(0);
    }

    txtQuantity.setText("");
    txtUnitPrice.setText("");
    txtSubtotal.setText("");

    selectedDetailId = -1;

    tblPurchaseDetails.clearSelection();
}

