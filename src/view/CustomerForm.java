    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int row = jTable2.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer first.");
    return;
}
Customer customer = new Customer();

customer.setCustomerName(txtCustomerName.getText());
customer.setPhone(txtPhone.getText());
customer.setEmail(txtEmail.getText());
customer.setAddress(txtaddress.getText());
customer.setCustomerId(
    customerService.getAllCustomers().get(row).getCustomerId()
);
boolean result = customerService.updateCustomer(customer);
if (result) {
    javax.swing.JOptionPane.showMessageDialog(this, "Customer Updated Successfully!");
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Failed to Update Customer!");
}


    }//GEN-LAST:event_jButton2ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int row = jTable2.getSelectedRow();

if (row != -1) {
    txtCustomerName.setText(jTable2.getValueAt(row, 0).toString());
    txtPhone.setText(jTable2.getValueAt(row, 1).toString());
    txtEmail.setText(jTable2.getValueAt(row, 2).toString());
    txtaddress.setText(jTable2.getValueAt(row, 3).toString());
    selectedCustomerId =
        customerService.getAllCustomers().get(row).getCustomerId();
}
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int row = jTable2.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a customer first.");
    return;
}

int customerId = customerService.getAllCustomers().get(row).getCustomerId();

boolean result = customerService.deleteCustomer(customerId);

if (result) {
    javax.swing.JOptionPane.showMessageDialog(this, "Customer Deleted Successfully!");
    loadCustomers();
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Failed to Delete Customer!");
}
    }//GEN-LAST:event_jButton3ActionPerformed

