    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       
        System.out.println("BUTTON CLICKED");
        String name = txtCustomerName.getText();
        String phone = txtPhone.getText();
        String email = txtEmail.getText();
        String address = txtaddress.getText();
        if (name.isEmpty() || phone.isEmpty() || email.isEmpty() || address.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!");
    return;
}
        if (!phone.matches("\\d+")) {
    javax.swing.JOptionPane.showMessageDialog(this, "Phone number must contain numbers only!");
    return;
}
        if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid email address!");
    return;
}

Customer customer = new Customer(
        0,
        name,
        phone,
        email,
        address
);



CustomerService service = new CustomerService();

boolean result = service.addCustomer(customer);

if (result) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Customer Added Successfully!"
    );
} else {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to Add Customer!"
    );
}// TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

