    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     String name = txtEmployeeName.getText().trim();
String phone = txtEmployeePhone.getText().trim();
String email = txtEmployeeEmail.getText().trim();
String position = txtEmployeePosition.getText().trim();
String status = cmbEmployeeStatus.getSelectedItem().toString();

if (name.isEmpty() || phone.isEmpty() || email.isEmpty() || position.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill all fields!"
    );
    return;
}

if (!phone.matches("\\d+")) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Phone number must contain numbers only!"
    );
    return;
}

if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter a valid email address!"
    );
    return;
}

String sql = "INSERT INTO employees "
        + "(employee_name, phone, email, position, status) "
        + "VALUES (?, ?, ?, ?, ?)";

try (Connection con = DBConnection.getConnection();
     PreparedStatement pst = con.prepareStatement(sql)) {

    pst.setString(1, name);
    pst.setString(2, phone);
    pst.setString(3, email);
    pst.setString(4, position);
    pst.setString(5, status);

    int result = pst.executeUpdate();

    if (result > 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Employee Added Successfully!"
        );

        loadEmployees();

        txtEmployeeName.setText("");
        txtEmployeePhone.setText("");
        txtEmployeeEmail.setText("");
        txtEmployeePosition.setText("");
        cmbEmployeeStatus.setSelectedIndex(0);
    }

} catch (Exception e) {
    e.printStackTrace();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to Add Employee!"
    );
}
    }//GEN-LAST:event_jButton1ActionPerformed

