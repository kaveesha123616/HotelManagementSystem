     private void loadSalesToCombo() {

    cmbSale.removeAllItems();

    SaleDAO dao = new SaleDAO();

    for (Sale sale : dao.getAllSales()) {

        cmbSale.addItem(
                String.valueOf(sale.getSaleId())
        );
    }
}

    private void loadPayments() {

    java.util.List<model.Payment> payments =
            paymentService.getAllPayments();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblPayments.getModel();

    model.setRowCount(0);

    for (model.Payment payment : payments) {

        model.addRow(new Object[]{
            payment.getPaymentId(),
            payment.getSaleId(),
            payment.getAmount(),
            payment.getPaymentMethod(),
            payment.getPaymentDate()
        });
    }
}
    

